def apply_suppressions(stack: Stack, cfg: dict[str, Any], base_model: str) -> None:
    for path, acks in acknowledgements(stack, cfg, base_model).items():
        target = _find(stack, path)
        for rule, reason in acks:
            Validations.of(target).acknowledge(Acknowledgment(id=rule, reason=reason))
