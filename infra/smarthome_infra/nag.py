def _index(stack: Stack, table: str) -> str:
    logical = stack.get_logical_id(_find(stack, table).node.default_child)
    return f"{P}IAM5[Resource::<{logical}.Arn>/index/*]"


def _find(stack: Stack, path: str) -> IConstruct:
    node: Any = stack
    for part in path.split("/"):
        node = node.node.find_child(part)
    return node


