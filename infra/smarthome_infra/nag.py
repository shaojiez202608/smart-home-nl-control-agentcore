"""cdk-nag acknowledgements, each attached to the construct it is about.

Every acknowledgement carries a written reason; the same list is summarised in
SECURITY-NOTES.md (with the construct paths). Nothing is acknowledged for the
whole stack: a new finding on another construct fails `cdk synth`. Rule ids
that contain configured values (topic prefix, resource prefix, model id) are
built from the configuration, so changing the configuration keeps the
acknowledgements aligned instead of silently failing or over-matching.

Prefer fixing over acknowledging: entries here are either inherent to the
service integration or deliberate prototype scope limits.
"""

